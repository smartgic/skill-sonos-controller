def fields(lines: tuple[str, ...]) -> set[str]:
    """Return every format field used by a sequence of dialog lines."""
    return {
        field
        for line in lines
        for _, field, _, _ in Formatter().parse(line)
        if field is not None
    }


def reference_files(directory: str, suffix: str) -> set[str]:
    """Read the English schema filenames for one resource type."""
    return {
        path.name
        for path in (LOCALE_ROOT / "en-us" / directory).glob(f"*{suffix}")
    }


def validate() -> None:
    """Fail before writing if the catalog does not match the English schema."""
    expected_dialogs = reference_files("dialog", ".dialog")
    expected_intents = reference_files("intents", ".intent")
    if set(DIALOGS) != set(GENERATED_LOCALES):
        raise ValueError("dialog locales do not match GENERATED_LOCALES")
    if set(INTENTS) != set(GENERATED_LOCALES):
        raise ValueError("intent locales do not match GENERATED_LOCALES")
    if set(META) != set(GENERATED_LOCALES):
        raise ValueError("locale metadata does not match GENERATED_LOCALES")
    if set(CODE_META) != set(ALL_LOCALES):
        raise ValueError("code metadata does not match ALL_LOCALES")
    if not set(LOCALE_ALIASES.values()) <= set(GENERATED_LOCALES):
        raise ValueError("locale aliases must reference generated locales")

    for locale in GENERATED_LOCALES:
        if set(DIALOGS[locale]) != expected_dialogs:
            missing = expected_dialogs - set(DIALOGS[locale])
            extra = set(DIALOGS[locale]) - expected_dialogs
            raise ValueError(f"{locale} dialog mismatch: missing={missing}, extra={extra}")
        if set(INTENTS[locale]) != expected_intents:
            missing = expected_intents - set(INTENTS[locale])
            extra = set(INTENTS[locale]) - expected_intents
            raise ValueError(f"{locale} intent mismatch: missing={missing}, extra={extra}")
        for name, localized_lines in DIALOGS[locale].items():
            english_lines = tuple(
                line
                for line in (LOCALE_ROOT / "en-us" / "dialog" / name)
                .read_text(encoding="utf-8")
                .splitlines()
                if line.strip()
            )
            if fields(localized_lines) != fields(english_lines):
                raise ValueError(
                    f"{locale}/{name} fields {fields(localized_lines)} do not match "
                    f"English fields {fields(english_lines)}"
                )
        if any(not lines or any(not line.strip() for line in lines) for lines in INTENTS[locale].values()):
            raise ValueError(f"{locale} contains an empty intent")


def render_codes(
    as_in: str, number_prefix: str, numbers: tuple[str, ...]
) -> str:
    """Render a localized spelling alphabet and digit vocabulary."""
    letters = (
        f"'{letter}' {as_in} {word},{letter}"
        for letter, word in zip("ABCDEFGHIJKLMNOPQRSTUVWXYZ", CODE_WORDS, strict=True)
    )
    number_lines = (
        f"{number_prefix} {numbers[number]},{number}"
        for number in range(10)
    )
    return "\n".join((*letters, *number_lines)) + "\n"


def write_lines(path: Path, lines: tuple[str, ...]) -> None:
    """Write one UTF-8 resource with a stable trailing newline."""
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")


def main() -> None:
    """Validate and generate every catalog resource."""
    validate()
    for locale in GENERATED_LOCALES:
        as_in, number_prefix, numbers, aliases = META[locale]
        data = LocaleData(
            dialogs=DIALOGS[locale],
            intents=INTENTS[locale],
            library_aliases=aliases,
        )
        root = LOCALE_ROOT / locale
        for name, lines in data.dialogs.items():
            write_lines(root / "dialog" / name, lines)
        for name, lines in data.intents.items():
            write_lines(root / "intents" / name, lines)
        write_lines(
            root / "intents" / "service.entity",
            (*SERVICES, *data.library_aliases),
        )
    for locale, source_locale in LOCALE_ALIASES.items():
        data = LocaleData(
            dialogs=DIALOGS[source_locale],
            intents=INTENTS[source_locale],
            library_aliases=META[source_locale][3],
        )
        root = LOCALE_ROOT / locale
        for name, lines in data.dialogs.items():
            write_lines(root / "dialog" / name, lines)
        for name, lines in data.intents.items():
            write_lines(root / "intents" / name, lines)
        write_lines(
            root / "intents" / "service.entity",
            (*SERVICES, *data.library_aliases),
        )
    for locale, (as_in, number_prefix, numbers, _) in CODE_META.items():
        path = LOCALE_ROOT / locale / "dialog" / "codes.value"
        path.write_text(
            render_codes(as_in, number_prefix, numbers), encoding="utf-8"
        )


if __name__ == "__main__":
    main()
